// Helper to generate a realistic 43-seat layout for Shivneri 2x2 AC coaches
export function generateBusSeats(serviceId: string, basePrice: number) {
  const seats = [];
  const occupiedSeed = serviceId.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
  
  // 11 rows of 4 seats (2 on left, 2 on right) + 1 back row
  let seatNum = 1;
  for (let r = 1; r <= 11; r++) {
    for (let c = 1; c <= 4; c++) {
      if (seatNum > 43) break;
      const id = `${serviceId}-S${seatNum}`;
      // Deterministic occupancy based on seed
      const pseudoRand = ((occupiedSeed * 37 + seatNum * 19) % 100);
      let status: 'available' | 'occupied' | 'female_reserved' = 'available';
      if (pseudoRand < 35) {
        status = 'occupied';
      } else if (pseudoRand < 48 && (c === 1 || c === 4)) {
        status = 'female_reserved';
      }

      // Window seat slight premium or uniform base
      const price = (c === 1 || c === 4) ? basePrice : basePrice;

      seats.push({
        id,
        seatNumber: `${seatNum}`,
        row: r,
        col: c,
        status,
        price
      });
      seatNum++;
    }
  }
  return seats;
}
